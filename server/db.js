import fs from 'node:fs';
import path from 'node:path';
import { AsyncLocalStorage } from 'node:async_hooks';
import pg from 'pg';

// Variabel lingkungan lokal dibaca dari .env (tidak ikut ke Git). Di Render diisi lewat dashboard.
const ENV_FILE = path.join(import.meta.dirname, '..', '.env');
if (fs.existsSync(ENV_FILE)) process.loadEnvFile(ENV_FILE);

if (!process.env.DATABASE_URL) {
  throw new Error('DATABASE_URL belum diatur. Salin .env.example menjadi .env lalu isi connection string PostgreSQL (mis. dari Neon).');
}

// COUNT/SUM integer dikembalikan PostgreSQL sebagai bigint (string); ubah ke number.
pg.types.setTypeParser(pg.types.builtins.INT8, (v) => parseInt(v, 10));
pg.types.setTypeParser(pg.types.builtins.NUMERIC, (v) => parseFloat(v));

export const pool = new pg.Pool({ connectionString: process.env.DATABASE_URL, max: 10 });

// Waktu UTC dalam format teks yang sama dengan sebelumnya ('YYYY-MM-DD HH:MM:SS').
export const NOW = "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')";

const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          TEXT NOT NULL,
  email         TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL,
  role          TEXT NOT NULL DEFAULT 'freemium' CHECK (role IN ('freemium', 'pro')),
  pro_until     TEXT,
  business_name TEXT NOT NULL,
  business_type TEXT NOT NULL CHECK (business_type IN ('katering', 'warung', 'rumah_makan')),
  city          TEXT,
  phone         TEXT,
  created_at    TEXT NOT NULL DEFAULT ${NOW}
);

-- UC-02: bahan baku beserta kategori (segar / tahan lama) yang menentukan periode forecast
CREATE TABLE IF NOT EXISTS ingredients (
  id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id         INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name            TEXT NOT NULL,
  unit            TEXT NOT NULL,
  category        TEXT NOT NULL CHECK (category IN ('segar', 'tahan_lama')),
  shelf_life_days INTEGER NOT NULL CHECK (shelf_life_days >= 1),
  min_stock       DOUBLE PRECISION NOT NULL DEFAULT 0,
  price           DOUBLE PRECISION NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS products (
  id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name    TEXT NOT NULL,
  price   DOUBLE PRECISION NOT NULL DEFAULT 0,
  active  INTEGER NOT NULL DEFAULT 1
);

-- Komposisi bahan per porsi menu
CREATE TABLE IF NOT EXISTS recipes (
  product_id    INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  ingredient_id INTEGER NOT NULL REFERENCES ingredients(id) ON DELETE CASCADE,
  qty           DOUBLE PRECISION NOT NULL CHECK (qty > 0),
  PRIMARY KEY (product_id, ingredient_id)
);

-- Stok masuk (per batch, supaya tanggal kedaluwarsa tiap pembelian bisa dilacak)
CREATE TABLE IF NOT EXISTS batches (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  ingredient_id INTEGER NOT NULL REFERENCES ingredients(id) ON DELETE CASCADE,
  qty           DOUBLE PRECISION NOT NULL CHECK (qty > 0),
  unit_price    DOUBLE PRECISION,
  received_date TEXT NOT NULL,
  expiry_date   TEXT NOT NULL,
  source        TEXT NOT NULL DEFAULT 'manual',
  created_at    TEXT NOT NULL DEFAULT ${NOW}
);

CREATE TABLE IF NOT EXISTS sales (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  product_id INTEGER NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  qty        INTEGER NOT NULL CHECK (qty > 0),
  date       TEXT NOT NULL,
  source     TEXT NOT NULL DEFAULT 'manual',
  created_at TEXT NOT NULL DEFAULT ${NOW}
);

CREATE TABLE IF NOT EXISTS waste_logs (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  ingredient_id INTEGER NOT NULL REFERENCES ingredients(id) ON DELETE CASCADE,
  qty           DOUBLE PRECISION NOT NULL CHECK (qty > 0),
  date          TEXT NOT NULL,
  reason        TEXT NOT NULL
);

-- Tahap 3: event tagging (Natal, Lebaran, gajian, event milik usaha)
CREATE TABLE IF NOT EXISTS events (
  id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id  INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name     TEXT NOT NULL,
  date     TEXT NOT NULL,
  impact   DOUBLE PRECISION NOT NULL DEFAULT 1,
  category TEXT NOT NULL DEFAULT 'custom'
);

CREATE TABLE IF NOT EXISTS model_state (
  user_id    INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  alpha      DOUBLE PRECISION NOT NULL,
  wape       DOUBLE PRECISION,
  samples    INTEGER NOT NULL DEFAULT 0,
  trained_at TEXT NOT NULL DEFAULT ${NOW}
);

CREATE TABLE IF NOT EXISTS integrations (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  provider     TEXT NOT NULL,
  connected_at TEXT NOT NULL DEFAULT ${NOW},
  last_sync    TEXT,
  UNIQUE (user_id, provider)
);

CREATE TABLE IF NOT EXISTS payments (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id      INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  plan         TEXT NOT NULL,
  amount       INTEGER NOT NULL,
  method       TEXT NOT NULL,
  status       TEXT NOT NULL,
  period_start TEXT NOT NULL,
  period_end   TEXT NOT NULL,
  created_at   TEXT NOT NULL DEFAULT ${NOW}
);

-- Feedback tetap disimpan (anonim) walaupun akun dihapus
CREATE TABLE IF NOT EXISTS feedback (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER REFERENCES users(id) ON DELETE SET NULL,
  rating     INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
  category   TEXT NOT NULL,
  message    TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT ${NOW}
);

CREATE INDEX IF NOT EXISTS idx_sales_user_date ON sales(user_id, date);
CREATE INDEX IF NOT EXISTS idx_batches_user ON batches(user_id, received_date);
CREATE INDEX IF NOT EXISTS idx_waste_user ON waste_logs(user_id, date);
CREATE INDEX IF NOT EXISTS idx_events_user_date ON events(user_id, date);
CREATE INDEX IF NOT EXISTS idx_ingredients_user ON ingredients(user_id);
CREATE INDEX IF NOT EXISTS idx_products_user ON products(user_id);
`;

export async function initDb() {
  await pool.query(SCHEMA);
}

// Query ditulis dengan placeholder '?' lalu diubah ke gaya PostgreSQL ($1, $2, ...).
const converted = new Map();
function toPg(sql) {
  let out = converted.get(sql);
  if (!out) {
    let i = 0;
    out = sql.replace(/\?/g, () => `$${++i}`);
    converted.set(sql, out);
  }
  return out;
}

// Di dalam tx(), semua query memakai koneksi transaksi yang sama dan dijalankan berurutan
// (satu koneksi PostgreSQL hanya bisa memproses satu query pada satu waktu).
const txClient = new AsyncLocalStorage();
function query(text, params) {
  const t = txClient.getStore();
  if (!t) return pool.query(text, params);
  const p = t.last.then(() => t.client.query(text, params));
  t.last = p.catch(() => {});
  return p;
}

export const db = {
  async all(sql, ...params) {
    return (await query(toPg(sql), params)).rows;
  },
  async get(sql, ...params) {
    return (await query(toPg(sql), params)).rows[0];
  },
  async run(sql, ...params) {
    const r = await query(toPg(sql), params);
    return { changes: r.rowCount };
  },
  // INSERT satu baris, mengembalikan id baru.
  async insert(sql, ...params) {
    return (await query(`${toPg(sql)} RETURNING id`, params)).rows[0].id;
  },
  // INSERT banyak baris sekaligus (dipecah per 500) agar import & data contoh tetap cepat ke database cloud.
  async insertMany(table, columns, rows, chunk = 500) {
    for (let s = 0; s < rows.length; s += chunk) {
      const part = rows.slice(s, s + chunk);
      const values = [];
      const tuples = part.map((r, i) => `(${r.map((_, j) => `$${i * columns.length + j + 1}`).join(', ')})`);
      for (const r of part) values.push(...r);
      await query(`INSERT INTO ${table} (${columns.join(', ')}) VALUES ${tuples.join(', ')}`, values);
    }
  },
};

export async function tx(fn) {
  if (txClient.getStore()) return fn();
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const result = await txClient.run({ client, last: Promise.resolve() }, fn);
    await client.query('COMMIT');
    return result;
  } catch (err) {
    await client.query('ROLLBACK');
    throw err;
  } finally {
    client.release();
  }
}
